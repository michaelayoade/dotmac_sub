document.addEventListener("DOMContentLoaded", () => {
    const profile = document.getElementById("radius_profile_id");
    const download = document.getElementById("speed_download_mbps");
    const upload = document.getElementById("speed_upload_mbps");
    const notice = document.getElementById("profile-speed-notice");
    if (!profile || !download || !upload || !notice) return;

    function showNotice() {
        const selected = profile.selectedOptions[0];
        const configuredDown = selected.dataset.downloadMbps;
        const configuredUp = selected.dataset.uploadMbps;
        const source = selected.dataset.rateSource;
        let message;
        let mismatch = false;
        if (!profile.value) {
            message = "An auto-generated profile uses the tariff speeds entered here.";
        } else if (source === "invalid_literal") {
            message = "The selected profile has a rate limit that cannot be verified. Choose a different profile or correct its rate limit.";
            mismatch = true;
        } else if (!configuredDown && !configuredUp) {
            message = "This profile has no configured speed. The tariff speeds entered here determine the plan rate.";
        } else {
            const expected = `${configuredDown || "—"}/${configuredUp || "—"}`;
            mismatch = (configuredDown && download.value.trim() !== "" && Number(download.value) !== Number(configuredDown)) ||
                (configuredUp && upload.value.trim() !== "" && Number(upload.value) !== Number(configuredUp));
            const authority = selected.dataset.rateNote || "";
            message = `Profile speed: ${expected} Mbps (download/upload). ${authority}`;
            if (mismatch) message += selected.dataset.autoGeneratedForOffer === "true"
                ? " This tariff's generated profile will refresh when its speed changes are saved."
                : selected.dataset.blocksMismatch === "true"
                    ? " Tariff and profile speeds differ. A new or changed mismatch is blocked; an unchanged existing pair can be retained."
                    : " Tariff and profile speed fields differ; review them before saving.";
            if (selected.dataset.blocksMismatch === "true" &&
                selected.dataset.autoGeneratedForOffer !== "true" &&
                [configuredDown, configuredUp].some(speed => speed && !Number.isInteger(Number(speed)))) {
                message += " This form accepts whole Mbps; choose a compatible profile.";
            }
        }
        notice.textContent = message;
        notice.classList.toggle("border-amber-400", Boolean(mismatch));
        notice.classList.toggle("bg-amber-50", Boolean(mismatch));
        notice.classList.toggle("dark:bg-amber-900/20", Boolean(mismatch));
    }

    profile.addEventListener("change", showNotice);
    download.addEventListener("input", showNotice);
    upload.addEventListener("input", showNotice);
    if (!notice.dataset.serverError) showNotice();

    const guarantee = document.getElementById("guaranteed_speed");
    const guaranteeUnit = document.getElementById("guaranteed-speed-unit");
    if (guarantee && guaranteeUnit) {
        const showGuaranteeUnit = () => {
            guaranteeUnit.textContent = guarantee.value === "relative" ? "(%)" :
                guarantee.value === "fixed" ? "(Mbps)" : "";
        };
        guarantee.addEventListener("change", showGuaranteeUnit);
        showGuaranteeUnit();
    }
});
